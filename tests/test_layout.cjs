'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const base=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(base,p),'utf8');
const app=read('public/assets/app.js'),styles=read('public/assets/styles.css'),globe=read('public/globus/index.html'),shell=read('src/components/SiteShell.astro'),sw=read('public/sw.js');
assert(!shell.includes('<PageFooter />'),'Site-wide footer must be removed');
assert(!app.includes('<div class="globe-area-title">'),'No repeated globe content header');
assert(!app.includes('class="globe-full-link"'),'No redundant globe top/fullscreen link');
assert(app.includes('function classScene(g)'),'Six grade illustrations must exist');
for(const g of [6,7,8,9,10,11])assert(app.includes(g+':['),'Missing animated frames for grade '+g);
assert(styles.includes('scene-reel')&&styles.includes('infinite'),'Grade illustrations must continually animate');
assert(styles.includes('prefers-reduced-motion'),'Grade animations need reduced-motion fallback');
assert(styles.includes('.geography-class-grid'),'Responsive six-grade grid missing');
assert(styles.includes('max-width:none'),'Work area should use screen width');
assert(!globe.includes('id="back"'),'Recursive site button must never return');
assert(globe.includes('class="grades" hidden'),'Standalone class buttons hidden in embedded UI');
assert(globe.includes('for(const other of')&&globe.includes('other.open=false'),'Accordion must keep only one list expanded');
assert(globe.includes("if(!(chosen&&activeWater))AREA_RENDER.draw"),'Duplicate lake ellipse must not render on verified water geometry');
assert(globe.includes("loadBelarusProtected()"),'OSM national park contours must load');
assert(globe.includes("authoritativeOnly"),'False approximate protected-area contours must be hidden');
assert(sw.includes('protected-belarus-osm.json'),'Protected OSM outlines must be offline-cached');
const park=read('scripts/prepare-belarus-osm.mjs');
for(const label of ['Беловежская пуща','Припятский','Нарочанский','Браславские озёра (нацпарк)'])assert(park.includes(label),'Missing park geometry mapping '+label);
console.log('Layout: one header, no footer, full-width globe, exclusive lists and grade-card animations: passed');
