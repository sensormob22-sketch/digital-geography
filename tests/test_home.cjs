const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'public/assets/app.js'),'utf8');
const home=fs.readFileSync(path.join(root,'public/assets/home.css'),'utf8');
const shell=fs.readFileSync(path.join(root,'src/components/SiteShell.astro'),'utf8');
const nav=fs.readFileSync(path.join(root,'src/components/TopNav.astro'),'utf8');
const menu=fs.readFileSync(path.join(root,'src/components/SideNav.astro'),'utf8');
const practical=fs.readFileSync(path.join(root,'public/works/9/3/index.html'),'utf8');
const globe=fs.readFileSync(path.join(root,'public/globus/index.html'),'utf8');
assert(app.includes("location.hash||'#home'"),'Homepage must be default route');
assert(app.includes("section==='home'?homepage()"),'Main content must render welcome page');
assert(app.includes("r.section!=='home'"),'Language picker must be available only on home');
assert(app.includes("homeMotion(r.section==='home')"),'Welcome motion must start only on homepage');
assert(app.includes("localStorage.setItem('geo_site_lang',lang)"),'Selected language must persist globally');
for(const lang of ['ru','be','en'])assert(app.includes(lang+':{home:'),'Welcome copy must be translated into '+lang);
assert(menu.includes('id="navHome"')&&menu.includes('href="#home"'),'All navigation should return to homepage');
assert(nav.includes('id="globalLanguageSwitch"'),'Single language control required');
assert(home.includes('prefers-reduced-motion')&&home.includes('home-earth')&&home.includes('home-features'),'Responsive accessible animated home required');
assert(shell.includes('id="pageContent"')&&shell.includes('<TopNav />'),'Site shell missing core navigation');
assert(!practical.includes('data-language="ru"'),'Meteolab must not display a language picker');
assert(practical.includes("localStorage.getItem('geo_site_lang')"),'Meteolab must read one global site language');
assert(!globe.includes('data-lang="ru"'),'Globe must not display independent language picker');
assert(globe.includes("localStorage.getItem('geo_site_lang')"),'Globe must read one global site language');
assert(globe.includes('belarus-relief-9.png')&&globe.includes('belarusTexture'),'Grade-9 DEM must be a separate regional texture');
assert(globe.includes('grade===9?7:1'),'Grade-9 globe camera must not zoom back to whole Earth');
assert(!shell.includes('<PageFooter />'),'No redundant bottom footer should remain');
assert(app.includes('globe-area--immersive'),'Full-width globe page should use single unified layout');
assert(app.includes("+'&embed=1'"),'Embedded globe must hide duplicate header and grade switch');
assert(app.includes('class-link-illustrated'),'Grade tiles require animated geography scenes');
for(const grade of [6,7,8,9,10,11])assert(app.includes(" "+grade+":{")||app.includes(" "+grade+":{tone:"),'Missing grade '+grade+' theme');
const globeCSS=fs.readFileSync(path.join(root,'public/globus/index.html'),'utf8');
assert(globeCSS.includes('embedded-globe .top')&&globeCSS.includes('embedded-globe .grades'),'Embedded duplicate toolbar must be hidden');
assert(globeCSS.includes('for(const other of'),'Nomenclature group accordion must close others');
const style=fs.readFileSync(path.join(root,'public/assets/styles.css'),'utf8');
assert(style.includes('grade-scenes')&&style.includes('prefers-reduced-motion'),'Looping responsive tiles must respect reduced motion');
assert(style.includes('globe-frame{height:max('),'Globe must fill freed vertical area');
console.log('Homepage, unified globe layout, animated class tiles, shared language and removed footer checks passed');
